#!/usr/bin/env node
// OFF MARKET CORRECTION PLAN — dry run only. Production carries rows labelled 'Withdrawn' by the old reconcile
// cron although the feed never delivers Withdrawn. The live check
// (docs/operations/evidence-2026-09-08/lifecycle/stored-withdrawn-vs-live.json, every stored row by ListingId)
// splits them into: still live as Closed → status must be Closed (sold / rented); absent from the feed → the last
// verified provider status is RESTORED from raw_data.StandardStatus (the old cron rewrote only `status`) and the
// presence fact sync_status = 'off_feed' is recorded — the Mallan Off Market state (Maya 2026-09-08). No status is
// manufactured: a row whose retained provider status is not on-market is listed for manual review, not updated.
// This script emits the plan (counts + SQL) for Maya's authorization. It executes NOTHING.
//   node scripts/lifecycle/off-market-correction-plan.mjs [--in=<live-check json>] [--out=<base>]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
const argv = process.argv.slice(2);
const arg = (n, d = null) => { const h = argv.find((a) => a.startsWith(`--${n}=`)); return h ? h.slice(n.length + 3) : d; };
const inPath = arg('in', 'docs/operations/evidence-2026-09-08/lifecycle/stored-withdrawn-vs-live.json');
const outBase = arg('out', 'docs/operations/evidence-2026-09-08/lifecycle/off-market-correction-plan');
const live = JSON.parse(readFileSync(inPath, 'utf8'));
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const ON_MARKET = ['Active', 'Pending', 'ComingSoon', 'ActiveUnderContract']; // lib/idx/reconcile-decision.ts ON_MARKET_STATUSES
const plan = { source: inPath, generatedAt: new Date().toISOString(), executes: false, rule: 'status := raw_data.StandardStatus (last verified), sync_status := off_feed, idx_display_yn := false; never a manufactured status', groups: {} };
const sql = [];
sql.push('-- OFF MARKET CORRECTION PLAN (dry run) — generated by scripts/lifecycle/off-market-correction-plan.mjs');
sql.push('-- Requires explicit authorization before execution. Wrap in a transaction; run on the canonical branch only.');
sql.push('-- The provider status is RESTORED from the retained provider row (raw_data.StandardStatus); the presence fact is recorded.');
sql.push('BEGIN;');
for (const [type, g] of Object.entries(live.groups)) {
  const closed = (g.presentRows || []).filter((r) => r.StandardStatus === 'Closed');
  const absent = g.absentIds || [];
  plan.groups[type] = { stored: g.stored, toClosed: closed.length, toOffMarket: absent.length, otherLive: (g.presentRows || []).length - closed.length };
  if (closed.length) {
    sql.push(`-- ${type}: ${closed.length} rows still live as Closed (${type === 'rent' ? 'rented' : 'sold'}) — stored 'Withdrawn' was wrong`);
    sql.push(`UPDATE listings SET status = 'Closed', sync_status = 'synced', idx_display_yn = false, status_changed_at = now()`);
    sql.push(`  WHERE status = 'Withdrawn' AND listing_type = ${q(type)} AND listing_id IN (${closed.map((r) => q(r.ListingId)).join(', ')});`);
  }
  if (absent.length) {
    sql.push(`-- ${type}: ${absent.length} rows absent from the current feed — restore the last verified provider status, record off_feed (Off Market)`);
    for (let i = 0; i < absent.length; i += 500) {
      const ids = absent.slice(i, i + 500).map(q).join(', ');
      sql.push(`UPDATE listings SET status = raw_data->>'StandardStatus', sync_status = 'off_feed', idx_display_yn = false`);
      sql.push(`  WHERE status = 'Withdrawn' AND listing_type = ${q(type)} AND raw_data->>'StandardStatus' IN (${ON_MARKET.map(q).join(', ')}) AND listing_id IN (${ids});`);
    }
    sql.push(`-- ${type}: rows whose retained provider status is NOT on-market are NOT updated — list them for manual review:`);
    sql.push(`-- SELECT listing_id, status, raw_data->>'StandardStatus' AS retained_provider_status FROM listings WHERE status = 'Withdrawn' AND listing_type = ${q(type)} AND (raw_data->>'StandardStatus' IS NULL OR raw_data->>'StandardStatus' NOT IN (${ON_MARKET.map(q).join(', ')}));`);
  }
}
sql.push(`-- Projection mirror (listing_search_projection.mls_status carries listings.status; idx_display_yn mirrors the gate):`);
sql.push(`UPDATE listing_search_projection p SET mls_status = l.status, idx_display_yn = false FROM listings l WHERE p.listing_id = l.listing_id AND p.mls_status = 'Withdrawn' AND (l.sync_status = 'off_feed' OR l.status = 'Closed');`);
sql.push('-- COMMIT only after Maya authorizes; otherwise ROLLBACK;');
mkdirSync(path.dirname(outBase), { recursive: true });
writeFileSync(`${outBase}.json`, JSON.stringify(plan, null, 2) + '\n');
writeFileSync(`${outBase}.sql`, sql.join('\n') + '\n');
console.log(JSON.stringify(plan.groups, null, 2));
