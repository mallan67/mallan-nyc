#!/usr/bin/env node
// DELISTED CORRECTION PLAN — dry run only. Production carries rows labelled 'Withdrawn' by the old
// reconcile cron although the feed never delivers Withdrawn. The live check
// (docs/operations/evidence-2026-09-08/lifecycle/stored-withdrawn-vs-live.json, every stored row by ListingId)
// splits them into: still live as Closed → status must be Closed (sold / rented); absent from the feed →
// Delisted. This script emits the plan (counts + SQL) for Maya's authorization. It executes NOTHING.
//   node scripts/lifecycle/delisted-correction-plan.mjs [--in=<live-check json>] [--out=<base>]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
const argv = process.argv.slice(2);
const arg = (n, d = null) => { const h = argv.find((a) => a.startsWith(`--${n}=`)); return h ? h.slice(n.length + 3) : d; };
const inPath = arg('in', 'docs/operations/evidence-2026-09-08/lifecycle/stored-withdrawn-vs-live.json');
const outBase = arg('out', 'docs/operations/evidence-2026-09-08/lifecycle/delisted-correction-plan');
const live = JSON.parse(readFileSync(inPath, 'utf8'));
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const plan = { source: inPath, generatedAt: new Date().toISOString(), executes: false, groups: {} };
const sql = [];
sql.push('-- DELISTED CORRECTION PLAN (dry run) — generated by scripts/lifecycle/delisted-correction-plan.mjs');
sql.push('-- Requires explicit authorization before execution. Wrap in a transaction; run on the canonical branch only.');
sql.push('BEGIN;');
for (const [type, g] of Object.entries(live.groups)) {
  const closed = (g.presentRows || []).filter((r) => r.StandardStatus === 'Closed');
  const absent = g.absentIds || [];
  plan.groups[type] = { stored: g.stored, toClosed: closed.length, toDelisted: absent.length, otherLive: (g.presentRows || []).length - closed.length };
  if (closed.length) {
    sql.push(`-- ${type}: ${closed.length} rows still live as Closed (${type === 'rent' ? 'rented' : 'sold'}) — stored 'Withdrawn' was wrong`);
    sql.push(`UPDATE listings SET status = 'Closed', idx_display_yn = false, status_changed_at = now()`);
    sql.push(`  WHERE status = 'Withdrawn' AND listing_type = ${q(type)} AND listing_id IN (${closed.map((r) => q(r.ListingId)).join(', ')});`);
  }
  if (absent.length) {
    sql.push(`-- ${type}: ${absent.length} rows absent from the entitled feed — no provider status; Delisted, never Withdrawn`);
    for (let i = 0; i < absent.length; i += 500) {
      sql.push(`UPDATE listings SET status = 'Delisted' WHERE status = 'Withdrawn' AND listing_type = ${q(type)} AND listing_id IN (${absent.slice(i, i + 500).map(q).join(', ')});`);
    }
  }
}
sql.push(`-- Projection mirror (listing_search_projection.mls_status carries listings.status):`);
sql.push(`UPDATE listing_search_projection p SET mls_status = l.status FROM listings l WHERE p.listing_id = l.listing_id AND p.mls_status = 'Withdrawn' AND l.status IN ('Delisted','Closed');`);
sql.push('-- COMMIT only after Maya authorizes; otherwise ROLLBACK;');
mkdirSync(path.dirname(outBase), { recursive: true });
writeFileSync(`${outBase}.json`, JSON.stringify(plan, null, 2) + '\n');
writeFileSync(`${outBase}.sql`, sql.join('\n') + '\n');
console.log(JSON.stringify(plan.groups, null, 2));
