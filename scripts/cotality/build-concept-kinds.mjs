#!/usr/bin/env node
/**
 * cotality:concept-kinds — the type of every Cotality field the CRM forms may claim with data-concept.
 *
 * Writes public/crm/js/forms/concept-kinds.js: window.COTALITY_FIELD_KINDS = { Field: kind }, from the live contract
 * (data/cotality-enums.live.json) and the CustomFields keys (compliance/rules/compliance-concepts.json). The forms use it
 * (js/forms/concept-emit.js) to send each claimed field as the right type. Do NOT hand-edit the output.
 *   i integer · n decimal · b boolean · d date · t date-time · s text · e single picklist · m multi-picklist
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (p) => JSON.parse(readFileSync(resolve(root, p), 'utf8'));
const contract = read('data/cotality-enums.live.json');
const customKeys = read('compliance/rules/compliance-concepts.json').customFieldKeys.keys;

const kindOf = (type) => {
  if (type === 'Edm.Boolean') return 'b';
  if (type === 'Edm.String') return 's';
  if (type === 'Edm.Date') return 'd';
  if (type === 'Edm.DateTimeOffset') return 't';
  if (/^Edm\.Int(16|32|64)$/.test(type)) return 'i';
  if (/^Edm\.(Decimal|Double|Single)$/.test(type)) return 'n';
  return /\.Multi\.|^Collection\(/.test(type) ? 'm' : 'e';
};
const customKind = (n) => (/YN$/.test(n) ? 'b' : /Timestamp$|DateTime$/.test(n) ? 't' : /(Total|Months|Feet|Inches|Year)$/.test(n) ? 'i' : /(Amount|Percent|Size|FAR)$/.test(n) ? 'n' : 's');

const kinds = {};
for (const [n, t] of Object.entries(contract.entities.Property)) kinds[n] = kindOf(t);
for (const [n, t] of Object.entries(contract.entities.CustomProperty)) if (n !== 'CustomFields' && !(n in kinds)) kinds[n] = kindOf(t);
for (const n of customKeys) if (!(n in kinds)) kinds[n] = customKind(n);
const sorted = Object.fromEntries(Object.entries(kinds).sort(([a], [b]) => a.localeCompare(b)));

writeFileSync(
  resolve(root, 'public/crm/js/forms/concept-kinds.js'),
  '// GENERATED by scripts/cotality/build-concept-kinds.mjs from the live Cotality contract. Do NOT hand-edit.\n' +
    '// i integer, n decimal, b boolean, d date, t date-time, s text, e single picklist, m multi-picklist.\n' +
    'window.COTALITY_FIELD_KINDS = ' + JSON.stringify(sorted) + ';\n',
);
console.log(`cotality:concept-kinds — ${Object.keys(sorted).length} fields`);
