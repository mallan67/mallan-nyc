#!/usr/bin/env node
/**
 * cotality:search-catalog — the list of every Cotality field the CRM search can address.
 *
 * Reads the live contract (data/cotality-enums.live.json), the list of fields Cotality lets us filter on
 * (data/cotality-filterable.live.json) and the CustomFields keys (compliance/rules/compliance-concepts.json) and writes
 * public/crm/js/search/search-field-catalog.js, which the search page loads. Same rules as lib/search/field-filters.ts
 * (a test keeps the two in step). Do NOT hand-edit the output.
 *
 * Usage: node scripts/cotality/build-search-catalog.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (p) => JSON.parse(readFileSync(resolve(root, p), 'utf8'));
const contract = read('data/cotality-enums.live.json');
const filterable = new Set(read('data/cotality-filterable.live.json').filterable);
const customFields = read('compliance/rules/compliance-concepts.json').customFieldKeys;
const customKeys = customFields.keys;

const NUMBER_TYPES = new Set(['Edm.Int16', 'Edm.Int32', 'Edm.Int64', 'Edm.Decimal', 'Edm.Double', 'Edm.Single']);
const kindOfType = (t) =>
  t === 'Edm.Boolean' ? 'boolean' : t === 'Edm.String' ? 'string' : t === 'Edm.Date' ? 'date' : t === 'Edm.DateTimeOffset' ? 'datetime' : NUMBER_TYPES.has(t) ? 'number' : 'enum';
// the key of the live picklist a field uses (the field's own name, else the name of its enumeration type)
const enumKey = (name, type) => {
  const typeName = String(type).replace(/^Collection\(/, '').replace(/\)$/, '').replace(/^.*\.Enums\.(?:Multi\.)?/, '');
  return contract.enums[name] ? name : contract.enums[typeName] ? typeName : null;
};
const usedEnums = new Set();
const customFieldsKind = (n) => customFields.kinds?.[n] ?? (/YN$/.test(n) ? 'boolean' : /Timestamp$|DateTime$/.test(n) ? 'datetime' : /(Total|Amount|Percent|Months|Feet|Inches|Year|Size|FAR)$/.test(n) ? 'number' : 'string');

const out = [];
const P = contract.entities.Property;
for (const [name, type] of Object.entries(P)) {
  const kind = kindOfType(type);
  const e = kind === 'enum' ? enumKey(name, type) : null;
  if (e) usedEnums.add(e);
  out.push({ n: name, k: kind, s: filterable.has(name) ? 1 : 0, src: 'p', e: e || undefined });
}
for (const [name, type] of Object.entries(contract.entities.CustomProperty)) {
  if (name in P || name === 'CustomFields') continue;
  const kind = kindOfType(type);
  const e = kind === 'enum' ? enumKey(name, type) : null;
  if (e) usedEnums.add(e);
  out.push({ n: name, k: kind, s: 0, src: 'c', e: e || undefined });
}
for (const name of customKeys) {
  if (name in P || name in contract.entities.CustomProperty) continue;
  out.push({ n: name, k: customFieldsKind(name), s: 0, src: 'f' });
}
out.sort((a, b) => a.n.localeCompare(b.n));
const compact = out.map((o) => (o.e ? o : { n: o.n, k: o.k, s: o.s, src: o.src }));
const enums = Object.fromEntries([...usedEnums].sort().map((k) => [k, contract.enums[k]]));

const body =
  '// GENERATED by scripts/cotality/build-search-catalog.mjs from the live Cotality contract. Do NOT hand-edit.\n' +
  '// n = Cotality field, k = kind, s = 1 when Cotality filters it server side (0 = filtered on the fetched page),\n' +
  '// src = p (Property) | c (CustomProperty) | f (CustomFields key), e = key of the live picklist in COTALITY_SEARCH_ENUMS.\n' +
  'window.COTALITY_SEARCH_ENUMS = ' + JSON.stringify(enums) + ';\n' +
  'window.COTALITY_SEARCH_FIELDS = ' + JSON.stringify(compact) + ';\n';
writeFileSync(resolve(root, 'public/crm/js/search/search-field-catalog.js'), body);
console.log(`cotality:search-catalog — ${compact.length} fields (${compact.filter((f) => f.s).length} filtered by Cotality, ${compact.filter((f) => !f.s).length} on the fetched page)`);
