#!/usr/bin/env node
/**
 * build.js — Assembles index-built.html from modular source files
 *
 * Reads index.html line by line, inlines all CSS, HTML partials, and JS
 * into a single standalone HTML file (like the original SEARCH-STANDALONE.html).
 *
 * Usage: node build.js
 * Output: index-built.html
 */

const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const OUTPUT = path.join(ROOT, 'index-built.html');

function readFile(relPath) {
    const fullPath = path.join(ROOT, relPath);
    if (!fs.existsSync(fullPath)) {
        console.error('ERROR: File not found: ' + relPath);
        process.exit(1);
    }
    return fs.readFileSync(fullPath, 'utf8');
}

// Strip </script> from JS content to prevent premature script block closure.
// The HTML parser closes the script block on </script> even inside JS comments.
// We replace the closing tag pattern with a safe version.
function escapeScriptClose(jsContent) {
    return jsContent.replace(/<\/script/gi, '< /script');
}

// The live Cotality search contract (data/cotality-enums.live.json, regenerated by
// `npm run cotality:pull`) in the compact form the browser needs: per Property field its
// operator kind, filter verdict and sale / rental record counts; picklist members and display
// labels for carried picklists; REBNY CustomFields keys. The server mapping layer
// (lib/search/crm-idx-filter.ts) reads the same file — one source, no copy to maintain.
function clientContract() {
    const live = JSON.parse(fs.readFileSync(path.join(ROOT, '..', '..', 'data', 'cotality-enums.live.json'), 'utf8'));
    const s = live.search;
    if (!s) {
        console.error('ERROR: data/cotality-enums.live.json has no search contract — run npm run cotality:pull');
        process.exit(1);
    }
    const n = (v) => (typeof v === 'number' ? v : 0);
    const property = {}, enums = {}, labels = {};
    for (const [field, r] of Object.entries(s.property)) {
        const sale = n(r.sale) || n(r.sampled && r.sampled.sale);
        const rental = n(r.rental) || n(r.sampled && r.sampled.rental);
        const row = { k: r.kind, f: r.filter, s: sale, r: rental };
        if (r.lookup) row.l = r.lookup;
        if (r.observed) row.o = { s: r.observed.sale || {}, r: r.observed.rental || {} };
        property[field] = row;
        if (r.lookup && (sale || rental) && live.enums[r.lookup]) {
            enums[r.lookup] = live.enums[r.lookup];
            if (s.lookups[r.lookup]) labels[r.lookup] = s.lookups[r.lookup];
        }
    }
    enums.StandardStatus = live.enums.StandardStatus;
    const custom = {};
    for (const [key, c] of Object.entries(s.custom_fields.keys)) {
        custom[key] = { k: c.kind, s: c.sale || 0, r: c.rental || 0, o: c.observed ? { s: c.observed.sale || {}, r: c.observed.rental || {} } : undefined };
    }
    // Resources the server searches through their link to Property (lib/search/crm-idx-filter.ts
    // JOIN_RESOURCES): their filterable fields with data, except identity/system columns and fields
    // Property itself carries (those are searched on Property directly).
    const LINKED = ['OpenHouse', 'PropertyRooms', 'CustomProperty', 'Member', 'Office'];
    const NOT_CRITERIA = /(Key$|KeyNumeric$|^ModificationTimestamp$|^Originating|^SourceSystem|RecordSignature|^HumanModified|^InputEntryOrder$|^CustomFields$|^ListingPermission$|^ListingId$|^OpenHouseId$)/;
    const resources = {};
    for (const name of LINKED) {
        const e = (s.resources || {})[name];
        if (!e || e.access !== 'OK') continue;
        const fields = {};
        for (const [field, f] of Object.entries(e.fields)) {
            if (f.filter !== 'SUPPORTED' || NOT_CRITERIA.test(field) || s.property[field]) continue;
            const perSide = f.sale !== undefined || f.rental !== undefined;
            const total = n(f.total) || n(f.sampled);
            if (!total) continue;
            const row = { k: f.kind, t: total, s: perSide ? n(f.sale) : total, r: perSide ? n(f.rental) : total };
            if ((f.kind === 'enum' || f.kind === 'multi') && live.enums[f.type]) {
                row.l = f.type;
                enums[f.type] = live.enums[f.type];
                if (s.lookups[f.type]) labels[f.type] = s.lookups[f.type];
            }
            fields[field] = row;
        }
        resources[name] = fields;
    }
    // Fair Housing: values whose provider label contains a prohibited term are never offered.
    const excluded = s.fair_housing_excluded || {};
    Object.keys(excluded).forEach((name) => {
        if (enums[name]) enums[name] = enums[name].filter((v) => excluded[name].indexOf(v) === -1);
    });
    return { pulledAt: s.pulled_at, types: s.types, property, enums, labels, custom, statusCounts: s.status_counts || null, mallanOffice: s.mallan_office || null, resources };
}

const lines = readFile('index.html').split('\n');
const output = [];
let stats = { cssInlined: 0, htmlInlined: 0, jsInlined: 0 };

for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const trimmed = line.trim();

    // ── Live Cotality search contract: <!-- @cotality-contract --> ──
    if (trimmed === '<!-- @cotality-contract -->') {
        const contract = JSON.stringify(clientContract());
        output.push('<script>');
        output.push('// ═══ data/cotality-enums.live.json (search contract, compact) ═══');
        output.push('window.COTALITY_SEARCH_CONTRACT = ' + escapeScriptClose(contract) + ';');
        output.push('</script>');
        stats.contractBytes = contract.length;
        continue;
    }

    // ── CSS: Replace <link rel="stylesheet" href="css/..."> ──
    const cssMatch = trimmed.match(/^<link\s+rel="stylesheet"\s+href="(css\/[^"]+)"/);
    if (cssMatch) {
        const cssPath = cssMatch[1];
        const content = readFile(cssPath);
        if (stats.cssInlined === 0) {
            output.push('    <style>');
        }
        output.push('    /* ═══ ' + cssPath + ' ═══ */');
        output.push(content);
        // Check if next line is also a CSS link; if not, close the style tag
        const nextTrimmed = (i + 1 < lines.length) ? lines[i + 1].trim() : '';
        if (!nextTrimmed.match(/^<link\s+rel="stylesheet"\s+href="css\//)) {
            output.push('    </style>');
        }
        stats.cssInlined++;
        continue;
    }

    // ── HTML: Replace <!-- @include path/to/file.html --> ──
    const includeMatch = trimmed.match(/^<!-- @include ([^\s]+) -->$/);
    if (includeMatch) {
        const htmlPath = includeMatch[1];
        const content = readFile(htmlPath);
        output.push('<!-- ═══ ' + htmlPath + ' ═══ -->');
        output.push(content);
        stats.htmlInlined++;
        continue;
    }

    // ── JS: Replace <script src="js/..."></script> or <script src="tests/..."></script> ──
    const scriptMatch = trimmed.match(/^<script\s+src="((?:js|tests)\/[^"]+)">\s*<\/script>$/);
    if (scriptMatch) {
        const jsPath = scriptMatch[1];
        const content = readFile(jsPath);
        const escaped = escapeScriptClose(content);
        output.push('<script>');
        output.push('// ═══ ' + jsPath + ' ═══');
        output.push(escaped);
        output.push('</script>');
        stats.jsInlined++;
        continue;
    }

    // ── Pass through all other lines ──
    output.push(line);
}

const result = output.join('\n');
fs.writeFileSync(OUTPUT, result, 'utf8');

const totalLines = result.split('\n').length;
const sizeKB = Math.round(fs.statSync(OUTPUT).size / 1024);
console.log('Built: ' + OUTPUT);
console.log('  Lines: ' + totalLines);
console.log('  Size:  ' + sizeKB + ' KB');
console.log('  CSS inlined:  ' + stats.cssInlined + ' files');
console.log('  HTML inlined: ' + stats.htmlInlined + ' files');
console.log('  JS inlined:   ' + stats.jsInlined + ' files');
console.log('  Cotality contract: ' + Math.round((stats.contractBytes || 0) / 1024) + ' KB');

// Validation
const scriptOpen = (result.match(/<script/g) || []).length;
const scriptClose = (result.match(/<\/script>/g) || []).length;
const divOpen = (result.match(/<div[\s>]/g) || []).length;
const divClose = (result.match(/<\/div>/g) || []).length;
console.log('  <script> tags: ' + scriptOpen + ' open, ' + scriptClose + ' close');
console.log('  <div> tags: ' + divOpen + ' open, ' + divClose + ' close (balance: ' + (divOpen - divClose) + ')');
